function isPendingPayment(status: unknown) {
  return String(status ?? "").toUpperCase() === "PENDING";
}

function samePaymentAmount(
  actualAmount: number,
  expectedAmount: number,
  currencyCode: PaymentCurrencyCode,
) {
  const tolerance = currencyCode === "KHR" ? 1 : 0.01;
  return Math.abs(Number(actualAmount) - Number(expectedAmount)) <= tolerance;
}

function buildPaymentCompletedMessage({
  orderId,
  crop,
  qty,
  amount,
  buyer,
  chatRoomId,
}: {
  orderId: string;
  crop: string;
  qty: string;
  amount: string;
  buyer: string;
  chatRoomId?: string | null;
}) {
  return [
    `PAYMENT_COMPLETED:${orderId}`,
    `crop:${crop.replace(/\s+/g, " ").trim() || "Crop"}`,
    `qty:${qty.replace(/\s+/g, " ").trim()}`,
    `amount:${amount}`,
    `buyer:${buyer.replace(/\s+/g, " ").trim() || "Buyer"}`,
    `chatRoomId:${chatRoomId ?? ""}`,
  ].join("\n");
}

